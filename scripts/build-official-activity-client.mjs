#!/usr/bin/env node

import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["src/activity-official-browser.js"],
  bundle: true,
  platform: "browser",
  target: "es2020",
  format: "iife",
  minify: true,
  legalComments: "none",
  write: false
});

const output = result.outputFiles?.[0]?.text;
if (!output) throw new Error("esbuild did not produce the official Activity client bundle.");

await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/activity-official-client-source.js",
  `// AUTO-GENERATED by scripts/build-official-activity-client.mjs. Do not hand edit.\n` +
    `export const OFFICIAL_ACTIVITY_CLIENT_SOURCE = ${JSON.stringify(output)};\n`,
  "utf8"
);

console.log(`Bundled official Discord Activity client (${output.length} bytes).`);
