import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { compileTelegramVisualManifest } from "../src/telegram-visual-contract.js";

const repo = "milesgoeswildtv/Afterdark-Visuals";
const projectId = "veil-arena";
const token = process.env.AFTERDARK_VISUALS_TOKEN || process.env.VISUALS_GITHUB_TOKEN || "";
const defaultPath = resolve(process.cwd(), "config/veil-arena.visual-defaults.json");
const outputPath = resolve(process.cwd(), "src/generated/telegram-visuals.js");

async function loadManifest() {
  if (!token) {
    return JSON.parse(await readFile(defaultPath, "utf8"));
  }
  const response = await fetch(
    "https://api.github.com/repos/" + repo + "/contents/projects/" + projectId + "/manifest.json?ref=main",
    {
      headers: {
        authorization: "Bearer " + token,
        accept: "application/vnd.github.raw+json",
        "x-github-api-version": "2022-11-28",
        "user-agent": "veil-arena-visual-compiler"
      }
    }
  );
  if (!response.ok) {
    throw new Error("Failed to fetch Afterdark visuals: " + response.status + " " + await response.text());
  }
  return JSON.parse(await response.text());
}

function js(value) {
  return JSON.stringify(value, null, 2);
}

const manifest = await loadManifest();
const compiled = compileTelegramVisualManifest(manifest);
await mkdir(resolve(process.cwd(), "src/generated"), { recursive: true });
await writeFile(
  outputPath,
  "// Generated by scripts/compile-telegram-visuals.mjs. Do not hand-edit.\n"
    + "export const TELEGRAM_VISUAL_CSS = " + JSON.stringify(compiled.css) + ";\n"
    + "export const TELEGRAM_VISUAL_ASSETS = Object.freeze(" + js(compiled.assets) + ");\n",
  "utf8"
);
console.log("Compiled Veil Arena visual revision " + Number(manifest.revision || 0) + (token ? " from Afterdark-Visuals." : " from local safe defaults."));
