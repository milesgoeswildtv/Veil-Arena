#!/usr/bin/env node

import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";

const result = await build({
  stdin: {
    contents: `import { DiscordSDK } from "@discord/embedded-app-sdk";\nglobalThis.__VEIL_OFFICIAL_DISCORD_SDK__ = DiscordSDK;`,
    resolveDir: process.cwd(),
    sourcefile: "veil-discord-sdk-entry.js"
  },
  bundle: true,
  platform: "browser",
  target: "es2020",
  format: "iife",
  minify: true,
  legalComments: "none",
  write: false
});

const output = result.outputFiles?.[0]?.text;
if (!output) throw new Error("esbuild did not produce the Discord SDK bundle.");

await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/discord-sdk-source.js",
  `// AUTO-GENERATED by scripts/build-discord-sdk.mjs. Do not hand edit.\n` +
    `export const OFFICIAL_DISCORD_SDK_VERSION = "2.5.0";\n` +
    `export const OFFICIAL_DISCORD_SDK_SOURCE = ${JSON.stringify(output)};\n`,
  "utf8"
);

console.log(`Bundled @discord/embedded-app-sdk 2.5.0 (${output.length} bytes).`);
